"""
Writes Localization/en-US.hjson and Localization/th-TH.hjson from the text tables in tools/data/loc/.

Every leaf in the tables is a pair (English, Thai), so both files always define exactly the same keys.
Guide texts live under Mods.KhuMue.Guide.* (see UI/Pages/PageKit.Root); tModLoader's own keys
(config labels, keybind name) stay where tModLoader looks for them.

Run from the mod folder:  python tools/data/localization.py
"""
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
MODULES = ["loc_ui", "loc_entries", "loc_guides", "loc_misc"]


def load_module(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(HERE, "loc", name + ".py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def merge(target, source, path=""):
    for key, value in source.items():
        where = f"{path}.{key}" if path else key
        if isinstance(value, dict):
            node = target.setdefault(key, {})
            if not isinstance(node, dict):
                raise SystemExit(f"{where}: both a text and a group")
            merge(node, value, where)
        else:
            if key in target:
                raise SystemExit(f"{where}: defined twice")
            if not (isinstance(value, tuple) and len(value) == 2 and all(isinstance(v, str) for v in value)):
                raise SystemExit(f"{where}: expected (English, Thai)")
            target[key] = value


def emit(tree, lang, indent, out):
    tab = "\t" * indent
    for key, value in tree.items():
        if isinstance(value, dict):
            out.append(f"{tab}{key}: {{")
            emit(value, lang, indent + 1, out)
            out.append(f"{tab}}}")
        else:
            text = value[lang]
            out.append(f"{tab}{key}: {json.dumps(text, ensure_ascii=False)}")


def main():
    guide = {}
    mods = {}
    for name in MODULES:
        module = load_module(name)
        merge(guide, getattr(module, "GUIDE", {}))
        merge(mods, getattr(module, "MOD", {}))
    counts = []
    for lang, file in ((0, "en-US.hjson"), (1, "th-TH.hjson")):
        out = ["# Generated by tools/data/localization.py - edit the tables in tools/data/loc/ instead.", "Mods: {", "\tKhuMue: {"]
        emit(mods, lang, 2, out)
        out.append("\t\tGuide: {")
        emit(guide, lang, 3, out)
        out.append("\t\t}")
        out.append("\t}")
        out.append("}")
        path = os.path.join(ROOT, "Localization", file)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(out) + "\n")
        counts.append(sum(1 for line in out if line.rstrip().endswith('"')))
    print(f"wrote {counts[0]} keys per language")


if __name__ == "__main__":
    sys.exit(main())
